namespace Austral\CacheBundle\Cache;

use Austral\Contracts\Entity\EntityInterface;
use Doctrine\Persistence\Proxy;

/**
 * Builds the cache tags and keys. PSR-6 reserves the characters {}()/\@: in keys and tags: they are replaced.
 *
 * Tags of an entity: "austral.entity.<class>" and "austral.entity.<class>.<id>", the class name with dots
 * instead of backslashes (Austral\DomainBundle\Entity\Domain → austral.entity.Austral.DomainBundle.Entity.Domain).
 *
 * @author Matthieu Beurel <matthieu@austral.dev>
 *
 * @final
 */
class CacheTag
{
  public const string ENTITY_PREFIX = 'austral.entity.';
  public const string RENDER_PREFIX = 'austral.render.';

  /**
   * @param class-string $class
   *
   * @return string
   */
  public static function forClass(string $class): string
  {
    return self::ENTITY_PREFIX.self::sanitize(str_replace('\\', '.', ltrim($class, '\\')));
  }

  /**
   * @param class-string $class
   * @param string|int   $id
   *
   * @return string
   */
  public static function forClassAndId(string $class, string|int $id): string
  {
    return self::forClass($class).'.'.self::sanitize((string) $id);
  }

  /**
   * Tags of an entity: its class, and its id when it is an Austral entity with an id.
   *
   * @param object $entity
   *
   * @return list<string>
   */
  public static function forEntity(object $entity): array
  {
    $class = self::realClass($entity);
    $tags = [self::forClass($class)];
    if ($entity instanceof EntityInterface)
    {
      $id = self::idOf($entity);
      if (null !== $id)
      {
        $tags[] = self::forClassAndId($class, $id);
      }
    }

    return $tags;
  }

  /**
   * Most precise tag of an entity: "austral.entity.<class>.<id>", or the tag of its class when it has no id.
   * A render is tagged with it, so that saving one entity only invalidates the renders that use it.
   *
   * @param object $entity
   *
   * @return string
   */
  public static function ofEntity(object $entity): string
  {
    $tags = self::forEntity($entity);

    return $tags[count($tags) - 1];
  }

  /**
   * @param string          $name
   * @param string|int|null $id
   *
   * @return string
   */
  public static function forRender(string $name, string|int|null $id = null): string
  {
    return self::RENDER_PREFIX.self::sanitize($name).(null !== $id ? '.'.self::sanitize((string) $id) : '');
  }

  /**
   * Class of the entity, without the Doctrine proxy class.
   *
   * @param object $entity
   *
   * @return class-string
   */
  public static function realClass(object $entity): string
  {
    if ($entity instanceof Proxy)
    {
      $parent = get_parent_class($entity);
      if (false !== $parent)
      {
        return $parent;
      }
    }

    return $entity::class;
  }

  /**
   * Id of the entity, or null when it has none yet (new entity whose id is generated by the database).
   *
   * @param EntityInterface<object> $entity
   *
   * @return string|null
   */
  public static function idOf(EntityInterface $entity): ?string
  {
    try
    {
      $id = $entity->getId();
    }
    catch (\Error)
    {
      return null;
    }

    return '' !== $id ? $id : null;
  }

  /**
   * @param string $value
   *
   * @return string
   */
  public static function sanitize(string $value): string
  {
    return strtr($value, ['{' => '_', '}' => '_', '(' => '_', ')' => '_', '/' => '_', '\\' => '_', '@' => '_', ':' => '_']);
  }
}
